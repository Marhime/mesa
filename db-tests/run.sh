#!/usr/bin/env bash
# Runs the migrations and the SQL tests on a throwaway local Postgres.
set -euo pipefail
cd "$(dirname "$0")/.."

# initdb refuses to run as root: re-run as the postgres account when needed.
if [ "$(id -u)" = "0" ] && id postgres >/dev/null 2>&1; then
  chmod -R a+rX . 2>/dev/null || true
  exec runuser -u postgres -- bash "$0" "$@"
fi

PGBIN="${PGBIN:-/usr/lib/postgresql/16/bin}"
DATA="$(mktemp -d)"
PORT="${PGPORT_TEST:-54329}"
trap '"$PGBIN/pg_ctl" -D "$DATA" -m immediate stop >/dev/null 2>&1 || true; rm -rf "$DATA"' EXIT

"$PGBIN/initdb" -D "$DATA" -U postgres -A trust >/dev/null
"$PGBIN/pg_ctl" -D "$DATA" -o "-p $PORT -k $DATA -c listen_addresses=''" -w start >/dev/null

PSQL=(psql -X -q -v ON_ERROR_STOP=1 -h "$DATA" -p "$PORT" -U postgres -d postgres)
"${PSQL[@]}" -f db-tests/stubs.sql
for f in supabase/migrations/*.sql; do
  echo "migrate: $f"
  "${PSQL[@]}" -f "$f"
done

# The latest schema in one file (committed): what the migrations add up to, so nobody has to replay 25 files
# in their head. Then the reference rows the code relies on (job_kinds: packages/shared/test/job-kinds.test.ts).
# pg_dump's \restrict lines carry a random key: left out, so the file only changes when the schema does.
SCHEMA_OUT="${SCHEMA_OUT:-db-tests/schema.sql}"
DUMP=("$PGBIN/pg_dump" -h "$DATA" -p "$PORT" -U postgres -d postgres --no-owner)
{
  echo "-- Generated by db-tests/run.sh after every migration: the public schema, then the job_kinds rows."
  echo "-- Do not edit: write a migration, then run the db tests."
  "${DUMP[@]}" --schema-only --schema=public
  "${DUMP[@]}" --data-only --column-inserts --table=public.job_kinds
} | grep -Ev '^\\(un)?restrict ' > "$DATA/schema.sql"
cp "$DATA/schema.sql" "$SCHEMA_OUT"
echo "schema: $SCHEMA_OUT"
for t in db-tests/test.sql db-tests/test_pantry.sql db-tests/test_upkeep.sql db-tests/test_scans.sql db-tests/test_import_feedback.sql db-tests/test_amounts.sql db-tests/test_by_type.sql db-tests/test_safety.sql db-tests/test_ai.sql db-tests/test_creators.sql db-tests/test_creator_news.sql db-tests/test_smart.sql db-tests/test_fast_lane.sql db-tests/test_vague.sql db-tests/test_reread.sql db-tests/test_reread_all.sql db-tests/test_job_kinds.sql db-tests/test_live_edits.sql db-tests/test_sections.sql db-tests/test_job_safety.sql db-tests/test_invites_spend.sql db-tests/test_parts.sql db-tests/test_api_links.sql; do  # in order: each builds on the last
  echo "test: $t"
  "${PSQL[@]}" -f "$t"
done
