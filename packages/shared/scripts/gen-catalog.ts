// Turns packages/shared/catalog/catalog.json into supabase/migrations/20261105000005_catalog.sql.
// Run: pnpm --filter @mesa/shared gen:catalog
//
// The SQL is idempotent: product ids are md5('mesa-catalog:' || lower(name_en))::uuid, products and
// aliases are inserted with "on conflict do nothing", and aliases find their product by name.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { normalizeText, singularize } from '../src/normalize';
import type { Category, UnitFamily, Zone } from '../src/types';

const here = dirname(fileURLToPath(import.meta.url));
const CATALOG = resolve(here, '../catalog/catalog.json');
const OUT = resolve(here, '../../../supabase/migrations/20261105000005_catalog.sql');

const CATEGORIES: Category[] = ['produce', 'bakery', 'meat', 'dairy', 'frozen', 'cupboard', 'drinks', 'household', 'other'];
const ZONES: Zone[] = ['fridge', 'freezer', 'cupboard'];
const FAMILIES: UnitFamily[] = ['mass', 'volume', 'count', 'other'];
const LANGS = ['en', 'es', 'fr'] as const;

export interface CatalogEntry {
  name_en: string;
  category: Category;
  default_zone: Zone;
  shelf_life_days: number | null;
  is_staple: boolean;
  unit_family: UnitFamily;
  aliases: { en: string[]; es: string[]; fr: string[] };
}

interface AliasRow {
  name_en: string;
  alias: string;
  lang: string;
}

/** Throws with every problem found, so the catalog is fixed in one pass. */
export function validate(entries: CatalogEntry[]): AliasRow[] {
  const errors: string[] = [];
  const names = new Map<string, string>();
  const owners = new Map<string, string>(); // alias key (raw and singular) → product
  const rows: AliasRow[] = [];

  for (const [i, p] of entries.entries()) {
    const where = `#${i} ${p.name_en ?? '(no name)'}`;
    if (typeof p.name_en !== 'string' || p.name_en.trim() !== p.name_en || p.name_en.length === 0) errors.push(`${where}: bad name_en`);
    const lower = String(p.name_en).toLowerCase();
    if (names.has(lower)) errors.push(`${where}: duplicate name_en`);
    names.set(lower, p.name_en);
    if (!CATEGORIES.includes(p.category)) errors.push(`${where}: bad category ${p.category}`);
    if (!ZONES.includes(p.default_zone)) errors.push(`${where}: bad default_zone ${p.default_zone}`);
    if (!FAMILIES.includes(p.unit_family)) errors.push(`${where}: bad unit_family ${p.unit_family}`);
    if (typeof p.is_staple !== 'boolean') errors.push(`${where}: is_staple must be boolean`);
    if (p.shelf_life_days !== null && !(Number.isInteger(p.shelf_life_days) && p.shelf_life_days > 0)) {
      errors.push(`${where}: shelf_life_days must be null or a positive integer`);
    }

    const own = new Set<string>();
    const add = (alias: string, lang: string): void => {
      if (own.has(alias)) return; // same word in two languages: keep the first
      own.add(alias);
      rows.push({ name_en: p.name_en, alias, lang });
      // Same keys the matcher uses: whole words, as written and singularized.
      const words = alias.split(/[^a-z0-9]+/).filter((w) => w.length > 0);
      for (const key of new Set([words.join(' '), words.map((w) => singularize(w)).join(' ')])) {
        const other = owners.get(key);
        if (other !== undefined && other !== p.name_en) errors.push(`${where}: alias "${alias}" also matches ${other}`);
        owners.set(key, p.name_en);
      }
    };
    for (const lang of LANGS) {
      const list = p.aliases?.[lang];
      if (!Array.isArray(list)) {
        errors.push(`${where}: aliases.${lang} must be an array`);
        continue;
      }
      for (const alias of list) {
        if (typeof alias !== 'string' || alias.length === 0) errors.push(`${where}: empty alias`);
        else if (alias !== normalizeText(alias)) errors.push(`${where}: alias "${alias}" is not normalized (lowercase, no accents)`);
        else add(alias, lang);
      }
    }
    add(normalizeText(p.name_en), 'en'); // the canonical name is always an alias too
  }
  if (errors.length > 0) throw new Error(`catalog.json has ${errors.length} problem(s):\n  ${errors.join('\n  ')}`);
  return rows;
}

const q = (s: string): string => `'${s.replace(/'/g, "''")}'`;

export function toSql(entries: CatalogEntry[], rows: AliasRow[]): string {
  const products = entries
    .map(
      (p) =>
        `  (${q(p.name_en)}, ${q(p.category)}, ${q(p.default_zone)}, ${p.shelf_life_days ?? 'null'}, ${p.is_staple}, ${q(p.unit_family)})`,
    )
    .join(',\n');
  const aliases = rows.map((r) => `  (${q(r.name_en)}, ${q(r.alias)}, ${q(r.lang)})`).join(',\n');
  return `-- Shared product catalog: ${entries.length} products, ${rows.length} aliases (en/es/fr).
-- GENERATED by packages/shared/scripts/gen-catalog.ts from packages/shared/catalog/catalog.json.
-- Do not edit by hand: change catalog.json and run \`pnpm --filter @mesa/shared gen:catalog\`.
-- Idempotent: stable ids (md5 of the lowercase name), "on conflict do nothing" everywhere,
-- aliases attach to the global product with the same name.

insert into public.products (id, household_id, name_en, category, default_zone, shelf_life_days, is_staple, unit_family)
select md5('mesa-catalog:' || lower(v.name_en))::uuid, null, v.name_en, v.category::public.category,
       v.default_zone::public.zone, v.shelf_life_days::int, v.is_staple, v.unit_family::public.unit_family
from (values
${products}
) as v(name_en, category, default_zone, shelf_life_days, is_staple, unit_family)
on conflict do nothing;

insert into public.product_aliases (product_id, alias, lang)
select p.id, v.alias, v.lang
from (values
${aliases}
) as v(name_en, alias, lang)
join public.products p on p.household_id is null and lower(p.name_en) = lower(v.name_en)
on conflict do nothing;
`;
}

function main(): void {
  const entries = JSON.parse(readFileSync(CATALOG, 'utf8')) as CatalogEntry[];
  const rows = validate(entries);
  writeFileSync(OUT, toSql(entries, rows));
  console.log(`wrote ${OUT}: ${entries.length} products, ${rows.length} aliases`);
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
